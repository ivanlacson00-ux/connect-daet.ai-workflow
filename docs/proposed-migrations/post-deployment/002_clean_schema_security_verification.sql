observed AS (
  SELECT e.table_name,
    e.expected_fk_count,
    c.oid AS relation_oid,
    c.relrowsecurity AS rls_enabled,
    count(k.oid)::integer AS foreign_key_count
  FROM expected_tables AS e
  LEFT JOIN pg_catalog.pg_namespace AS n
    ON n.nspname = 'public'
  LEFT JOIN pg_catalog.pg_class AS c
    ON c.relnamespace = n.oid
   AND c.relname = e.table_name
  LEFT JOIN pg_catalog.pg_constraint AS k
    ON k.conrelid = c.oid
   AND k.contype = 'f'
  GROUP BY e.table_name, e.expected_fk_count, c.oid, c.relrowsecurity
)
SELECT 'table.' || table_name AS check_name,
  CASE WHEN relation_oid IS NULL THEN 'FAIL'
       WHEN foreign_key_count <> expected_fk_count THEN 'FAIL'
       ELSE 'PASS' END AS status,
  format('exists=%s; foreign_keys=%s expected=%s',
    relation_oid IS NOT NULL, foreign_key_count, expected_fk_count) AS detail
FROM observed
UNION ALL
SELECT 'rls.' || table_name,
  CASE WHEN relation_oid IS NULL OR NOT coalesce(rls_enabled, false)
       THEN 'FAIL' ELSE 'PASS' END,
  format('exists=%s; rls_enabled=%s',
    relation_oid IS NOT NULL, coalesce(rls_enabled, false))
FROM observed
ORDER BY check_name;

